package mapper

import (
	"encoding/csv"
	"fmt"
	"strings"

	"terminology-mapper/dictionary"
	"terminology-mapper/matcher"
)

// ProcessItems runs the matching engine on a list of local hospital items.
func ProcessItems(items []dictionary.LocalItem, catalog []dictionary.StandardTerm) []dictionary.MappedRow {
	var results []dictionary.MappedRow

	for _, item := range items {
		matches := matcher.FindMatches(item, catalog, 3)

		row := dictionary.MappedRow{
			LocalCode:  item.LocalCode,
			LocalName:  item.LocalName,
			Category:   item.Category,
			Candidates: matches,
		}

		if len(matches) > 0 {
			best := matches[0]
			row.BestMatch = &best
			if best.Confidence >= 75 {
				row.IsApproved = true
			}
		}

		results = append(results, row)
	}

	return results
}

// GenerateSQLScript produces ready-to-run INSERT statements for SIMRS database.
func GenerateSQLScript(rows []dictionary.MappedRow, tableName string) string {
	if tableName == "" {
		tableName = "simrs_satusehat_mapping"
	}

	var sb strings.Builder
	sb.WriteString("-- Auto-generated by CortexCore :: TerminologyMapper Studio\n")
	sb.WriteString("-- Architected by Rashqa Andrean Fitrah Sulaeman\n\n")
	sb.WriteString(fmt.Sprintf("CREATE TABLE IF NOT EXISTS %s (\n", tableName))
	sb.WriteString("    local_code VARCHAR(64) PRIMARY KEY,\n")
	sb.WriteString("    local_name VARCHAR(255),\n")
	sb.WriteString("    category VARCHAR(32),\n")
	sb.WriteString("    standard_code VARCHAR(64),\n")
	sb.WriteString("    standard_name VARCHAR(255),\n")
	sb.WriteString("    system_uri VARCHAR(255),\n")
	sb.WriteString("    confidence INT,\n")
	sb.WriteString("    updated_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP\n")
	sb.WriteString(");\n\n")

	for _, r := range rows {
		code := ""
		name := ""
		sys := ""
		conf := 0

		if r.ManualCode != "" {
			code = r.ManualCode
			name = r.ManualName
			conf = 100
		} else if r.BestMatch != nil {
			code = r.BestMatch.StandardCode
			name = r.BestMatch.StandardName
			sys = r.BestMatch.SystemURI
			conf = r.BestMatch.Confidence
		}

		if code != "" {
			escape := func(s string) string { return strings.ReplaceAll(s, "'", "''") }
			sb.WriteString(fmt.Sprintf(
				"INSERT INTO %s (local_code, local_name, category, standard_code, standard_name, system_uri, confidence) VALUES ('%s', '%s', '%s', '%s', '%s', '%s', %d) ON CONFLICT (local_code) DO UPDATE SET standard_code = EXCLUDED.standard_code, standard_name = EXCLUDED.standard_name, confidence = EXCLUDED.confidence;\n",
				tableName,
				escape(r.LocalCode),
				escape(r.LocalName),
				r.Category,
				escape(code),
				escape(name),
				escape(sys),
				conf,
			))
		}
	}

	return sb.String()
}

// ExportCSV generates standardized CSV mapping output.
func ExportCSV(rows []dictionary.MappedRow) string {
	var sb strings.Builder
	w := csv.NewWriter(&sb)

	w.Write([]string{
		"local_code", "local_name", "category", "standard_code", "standard_name", "system_uri", "confidence_pct", "status",
	})

	for _, r := range rows {
		code, name, sys, status := "", "", "", "UNMAPPED"
		conf := 0
		if r.ManualCode != "" {
			code = r.ManualCode
			name = r.ManualName
			status = "MANUALLY_MAPPED"
			conf = 100
		} else if r.BestMatch != nil {
			code = r.BestMatch.StandardCode
			name = r.BestMatch.StandardName
			sys = r.BestMatch.SystemURI
			status = r.BestMatch.Status
			conf = r.BestMatch.Confidence
		}

		w.Write([]string{
			r.LocalCode,
			r.LocalName,
			string(r.Category),
			code,
			name,
			sys,
			fmt.Sprintf("%d", conf),
			status,
		})
	}

	w.Flush()
	return sb.String()
}
